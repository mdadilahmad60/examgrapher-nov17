/* ExamGrapher site search: animated placeholder + live suggestions.
   The tool index (assets/js/search-data.js, generated by scripts/build.py) is fetched on first focus. */
(function () {
  "use strict";
  var input = document.getElementById("siteSearch");
  if (!input) return;
  var box = document.getElementById("hsearch"), list = document.getElementById("searchList");
  var openBtn = document.getElementById("searchBtn"), closeBtn = document.getElementById("searchClose");
  var me = document.querySelector('script[src*="assets/js/search.js"]');
  var src = me ? me.src : "", base = src.replace(/assets\/js\/search\.js.*$/, ""), ver = (/[?&]v=([\w.-]+)/.exec(src) || [])[1] || "1";
  var hints = (input.getAttribute("data-hints") || "").split("|").filter(Boolean);
  var reduce = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var PRE = "Search for ";
  var data = null, pending = null, results = [], active = -1;

  /* ---------- animated placeholder: type a name, blink the cursor, erase, next name ---------- */
  var timer = 0, idx = 0, pos = 0, phase = "type", blinks = 0, caret = true, animating = false;
  function ph(t) { input.setAttribute("placeholder", t); }
  function tick() {
    var word = hints[idx], delay;
    if (phase === "type") {
      pos++; ph(PRE + word.slice(0, pos) + "|");
      if (pos >= word.length) { phase = "hold"; blinks = 0; caret = true; delay = 450; } else delay = 55 + Math.random() * 45;
    } else if (phase === "hold") {
      caret = !caret; blinks++; ph(PRE + word + (caret ? "|" : ""));
      delay = 330;
      if (blinks >= 8) { phase = "erase"; delay = 150; }
    } else {
      pos--; ph(PRE + word.slice(0, pos) + "|");
      if (pos <= 0) { idx = (idx + 1) % hints.length; phase = "type"; delay = 380; } else delay = 22;
    }
    timer = setTimeout(tick, delay);
  }
  function startAnim() {
    if (animating || !hints.length) return;
    if (reduce) { ph(PRE + hints[0]); return; }
    animating = true; phase = "type"; pos = 0; tick();
  }
  function stopAnim(text) { animating = false; clearTimeout(timer); if (text) ph(text); }
  document.addEventListener("visibilitychange", function () {
    if (document.hidden) stopAnim(); else if (!input.value && document.activeElement !== input) startAnim();
  });

  /* ---------- index ---------- */
  function load(cb) {
    if (data) return cb();
    if (window.EG_INDEX) { data = window.EG_INDEX; return cb(); }
    if (pending) { pending.push(cb); return; }
    pending = [cb];
    var s = document.createElement("script");
    s.src = base + "assets/js/search-data.js?v=" + ver;
    s.onload = function () { data = window.EG_INDEX || []; var q = pending; pending = null; q.forEach(function (f) { f(); }); };
    s.onerror = function () { pending = null; };
    document.head.appendChild(s);
  }
  /* entry = [title, path, category, description, keywords, popularFlag] */
  function score(e, toks) {
    var title = e[0].toLowerCase(), kw = e[4].toLowerCase(), rest = (e[2] + " " + e[3]).toLowerCase(), s = 0, i, t;
    for (i = 0; i < toks.length; i++) {
      t = toks[i];
      if (title.indexOf(t) === 0) s += 6; else if (title.indexOf(" " + t) >= 0) s += 5; else if (title.indexOf(t) >= 0) s += 4;
      else if (kw.indexOf(t) >= 0) s += 2; else if (rest.indexOf(t) >= 0) s += 1; else return -1;
    }
    return s;
  }
  function find(q) {
    var toks = q.toLowerCase().split(/[\s,]+/).filter(Boolean), out = [], i, s;
    if (!toks.length) return data.filter(function (e) { return e[5]; }).slice(0, 7);
    for (i = 0; i < data.length; i++) { s = score(data[i], toks); if (s >= 0) out.push({ e: data[i], s: s, i: i }); }
    out.sort(function (a, b) { return b.s - a.s || a.i - b.i; });
    return out.slice(0, 8).map(function (o) { return o.e; });
  }

  /* ---------- results list ---------- */
  function highlight(el, text, q) {
    var toks = q.toLowerCase().split(/[\s,]+/).filter(Boolean), low = text.toLowerCase(), hit = -1, len = 0, i, p;
    for (i = 0; i < toks.length; i++) { p = low.indexOf(toks[i]); if (p >= 0 && (hit < 0 || p < hit)) { hit = p; len = toks[i].length; } }
    if (hit < 0) { el.textContent = text; return; }
    el.appendChild(document.createTextNode(text.slice(0, hit)));
    var m = document.createElement("mark"); m.textContent = text.slice(hit, hit + len); el.appendChild(m);
    el.appendChild(document.createTextNode(text.slice(hit + len)));
  }
  function setActive(i) {
    var items = list.querySelectorAll(".sr-item"), k;
    active = items.length ? (i + items.length) % items.length : -1;
    for (k = 0; k < items.length; k++) items[k].setAttribute("aria-selected", k === active ? "true" : "false");
    if (active >= 0) { input.setAttribute("aria-activedescendant", items[active].id); items[active].scrollIntoView({ block: "nearest" }); }
    else input.removeAttribute("aria-activedescendant");
  }
  function render() {
    var q = input.value.trim(), frag = document.createDocumentFragment(), lab, i, a, t, c;
    results = find(q); list.textContent = "";
    if (!q) { lab = document.createElement("div"); lab.className = "sr-label"; lab.textContent = "Popular tools"; frag.appendChild(lab); }
    if (!results.length) {
      var em = document.createElement("div"); em.className = "sr-empty";
      em.textContent = "No tool matches \u201c" + q + "\u201d. Try graph, SAT, regression, circle or derivative.";
      frag.appendChild(em);
    }
    results.forEach(function (e, n) {
      a = document.createElement("a"); a.className = "sr-item"; a.id = "sr-" + n; a.href = base + e[1];
      a.setAttribute("role", "option"); a.setAttribute("aria-selected", "false");
      t = document.createElement("span"); t.className = "sr-t"; highlight(t, e[0], q);
      c = document.createElement("span"); c.className = "sr-c"; c.textContent = e[2];
      a.appendChild(t); a.appendChild(c);
      a.addEventListener("mousemove", function () { if (active !== n) setActive(n); });
      frag.appendChild(a);
    });
    list.appendChild(frag); list.hidden = false;
    input.setAttribute("aria-expanded", "true");
    setActive(results.length ? 0 : -1);
  }
  function closeList() { list.hidden = true; input.setAttribute("aria-expanded", "false"); input.removeAttribute("aria-activedescendant"); }
  function go() {
    var items = list.querySelectorAll(".sr-item");
    if (items.length) window.location.href = items[Math.max(active, 0)].href;
  }

  /* ---------- mobile: the magnifier turns the header into a search bar ---------- */
  function openBar() { box.classList.add("open"); if (openBtn) openBtn.setAttribute("aria-expanded", "true"); input.focus(); }
  function closeBar() {
    box.classList.remove("open"); if (openBtn) openBtn.setAttribute("aria-expanded", "false");
    closeList(); input.blur(); input.value = ""; startAnim();
  }
  if (openBtn) openBtn.addEventListener("click", openBar);
  if (closeBtn) closeBtn.addEventListener("click", closeBar);

  /* keep animating while the box is empty, even when focused; stop as soon as the person types */
  input.addEventListener("focus", function () { load(render); });
  input.addEventListener("input", function () { if (input.value) stopAnim(); else startAnim(); load(render); });
  input.addEventListener("blur", function () { if (!input.value) startAnim(); });
  input.addEventListener("keydown", function (e) {
    if (e.key === "ArrowDown") { e.preventDefault(); if (list.hidden) load(render); else setActive(active + 1); }
    else if (e.key === "ArrowUp") { e.preventDefault(); setActive(active - 1); }
    else if (e.key === "Enter") { e.preventDefault(); load(function () { if (list.hidden) render(); go(); }); }
    else if (e.key === "Escape") { if (input.value) { input.value = ""; render(); } else if (box.classList.contains("open")) closeBar(); else { closeList(); input.blur(); } }
  });
  document.addEventListener("pointerdown", function (e) {
    if (!box.contains(e.target) && (!openBtn || !openBtn.contains(e.target))) { closeList(); if (box.classList.contains("open")) closeBar(); }
  });
  /* press "/" or Ctrl/Cmd+K anywhere to jump to the search box */
  document.addEventListener("keydown", function (e) {
    var t = e.target, typing = t && (t.tagName === "INPUT" || t.tagName === "TEXTAREA" || t.tagName === "SELECT" || t.isContentEditable);
    if ((e.key === "/" && !typing && !e.ctrlKey && !e.metaKey && !e.altKey) || ((e.key === "k" || e.key === "K") && (e.ctrlKey || e.metaKey))) {
      e.preventDefault();
      if (window.getComputedStyle(box).display === "none") openBar(); else input.focus();
    }
  });
  setTimeout(startAnim, 500);
})();
